#!/usr/bin/env python3
"""
Generate the con3code yt-dlp plugin from this fork's extractor sources.

The fork's code in yt_dlp/extractor/ is the single source of truth.
This script copies the changed classes out of it and wraps them so that
upstream yt-dlp can load them with --plugin-dirs.

    python con3code_plugin/generate.py           # write the plugin files
    python con3code_plugin/generate.py --check   # fail if they are out of date
"""

import argparse
import ast
import pathlib
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / 'yt_dlp' / 'extractor'
# Pass PLUGINS_DIR to yt-dlp: --plugin-dirs con3code_plugin/plugins
PLUGINS_DIR = ROOT / 'con3code_plugin' / 'plugins'
OUT_DIR = PLUGINS_DIR / 'con3code' / 'yt_dlp_plugins' / 'extractor'
PLUGIN_NAME = 'con3code'


class Source:
    def __init__(self, module):
        self.module = module
        self.path = SRC_DIR / f'{module}.py'
        self.text = self.path.read_text(encoding='utf-8')
        self.tree = ast.parse(self.text)
        self.classes = {
            node.name: node for node in self.tree.body if isinstance(node, ast.ClassDef)}

    def imports(self):
        """The module's import block, with relative imports made absolute."""
        lines = []
        for node in self.tree.body:
            if not isinstance(node, ast.Import | ast.ImportFrom):
                continue
            if isinstance(node, ast.ImportFrom) and node.level:
                base = ['yt_dlp', 'extractor'][:3 - node.level]
                node = ast.ImportFrom(
                    module='.'.join([*base, *filter(None, [node.module])]), names=node.names, level=0)
            lines.append(ast.unparse(node))
        return '\n'.join(lines)

    def body(self, name):
        """Source of a class body, dedented, without the class line."""
        node = self.classes[name]
        lines = self.text.splitlines()
        start = node.body[0].lineno - 1
        # Include decorators/comments directly above the first statement
        if isinstance(node.body[0], ast.FunctionDef) and node.body[0].decorator_list:
            start = node.body[0].decorator_list[0].lineno - 1
        return textwrap.dedent('\n'.join(lines[start:node.end_lineno]))

    def class_source(self, name):
        node = self.classes[name]
        start = (node.decorator_list[0] if node.decorator_list else node).lineno - 1
        return '\n'.join(self.text.splitlines()[start:node.end_lineno])

    def valid_urls(self, name):
        for stmt in self.classes[name].body:
            if isinstance(stmt, ast.Assign) and any(
                    isinstance(t, ast.Name) and t.id == '_VALID_URL' for t in stmt.targets):
                value = ast.literal_eval(stmt.value)
                return [value] if isinstance(value, str) else list(value)
        raise ValueError(f'{name} has no literal _VALID_URL')


def indent(text):
    return textwrap.indent(text, '    ')


def header(source):
    return f'''\
# This file is generated by con3code_plugin/generate.py from
# yt_dlp/extractor/{source.module}.py of con3code/yt-dlp. Do not edit it by hand.
# ruff: noqa: E501, F401, I001
'''


def override(upstream_name, bodies):
    """An override of an upstream extractor whose body is the fork's code.

    The plugin system needs the upstream class directly after the override in the MRO,
    so the fork's base-class methods are copied into the body instead of being inherited.
    """
    joined = '\n\n'.join(bodies)
    return (f'class {upstream_name}(_upstream.{upstream_name}, plugin_name={PLUGIN_NAME!r}):\n'
            f'{indent(joined)}\n')


def gen_radiko():
    src = Source('radiko')
    share_urls = [u for u in src.valid_urls('RadikoIE') if '/share' in u]
    assert len(share_urls) == 1, 'expected exactly one share URL pattern in RadikoIE'
    base = src.body('RadikoBaseIE')

    return f'''{header(src)}
{src.imports()}

import yt_dlp.extractor.radiko as _upstream

# Only RadikoShareIE is a new extractor; the others override upstream ones
__all__ = ['RadikoShareIE']


{override('RadikoIE', [base, src.body('RadikoIE')])}

{override('RadikoRadioIE', [base, src.body('RadikoRadioIE')])}

class RadikoShareIE(InfoExtractor):
    # Overrides cannot change URL matching when upstream uses lazy extractors,
    # so share links get their own extractor and are handed to RadikoIE.
    IE_NAME = 'radiko:share'
    _VALID_URL = {share_urls[0]!r}

    def _real_extract(self, url):
        station, timestring = self._match_valid_url(url).group('station', 'timestring')
        return self.url_result(
            f'https://radiko.jp/#!/ts/{{station}}/{{timestring}}', RadikoIE,
            f'{{station}}-{{timestring}}')
'''


def gen_nhk():
    src = Source('nhk')
    return f'''{header(src)}
{src.imports()}

__all__ = ['NhkEduSchoolWatchIE']


{src.class_source('NhkEduSchoolWatchIE')}
'''


GENERATORS = {
    'con3code_radiko.py': gen_radiko,
    'con3code_nhk.py': gen_nhk,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='only check that the files are up to date')
    args = parser.parse_args()

    stale = []
    for filename, generate in GENERATORS.items():
        code = generate()
        compile(code, filename, 'exec')
        path = OUT_DIR / filename
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != code:
                stale.append(filename)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(code, encoding='utf-8')
        print(f'wrote {path.relative_to(ROOT)}')

    if stale:
        print(f'out of date: {", ".join(stale)}; run con3code_plugin/generate.py', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
